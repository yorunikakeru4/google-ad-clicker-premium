-- 004: убрать колонку proxies.country.
--
-- Страна прокси — не состояние строки, а геолокация exit-IP в конкретный
-- момент: её даёт только живой запрос через прокси, поэтому хранить её в
-- пуле означало либо платить за запрос на каждую проверку, либо показывать
-- устаревшее значение. Страна сессии по-прежнему видна в диагностике — там
-- она берётся из ``driver._geo_country`` в момент снятия снимка, то есть
-- отражает именно тот exit-IP, которым работал браузер.
--
-- Порядок: единственное утверждение и неидемпотентное — зеркало позиции
-- ALTER в 002/003 (см. докстринг engine/db/migrations.py). Обрыв между
-- ALTER и bump'ом версии даёт на повторе детерминированную ошибку «no such
-- column» и не теряет строки: колонка в тот момент уже удалена, данные
-- прокси (креды, счётчики, статусы) не тронуты.

ALTER TABLE proxies DROP COLUMN country;
