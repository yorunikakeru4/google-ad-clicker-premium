-- 002: произвольные поля профиля и нормализация статуса (фаза 6).
--
-- Контракт (план.md, §5 «Фаза 6», §2): у профиля есть произвольные поля
-- в JSON и пять статусов free|assigned|active|error|blocked. Старый default
-- 'new' не является ни одним из них, поэтому существующие строки приводятся к
-- 'free' ("свободен") — до того, как пул статусов начнёт ими управлять.
--
-- Порядок утверждений продикован неатомарностью executescript (см. докстринг
-- engine/db/migrations.py): UPDATE идемпотентен и стоит первым, ALTER —
-- единственное неидемпотентное утверждение и последнее. Обрыв после UPDATE
-- переживает повторный запуск без изменений; обрыв на ALTER даёт ту же самую
-- детерминированную ошибку ("duplicate column"), данные при этом не тронуты.
--
-- default колонки status в УЖЕ существующих таблицах остаётся 'new': SQLite
-- не меняет DEFAULT без пересоздания таблицы, а пересоздание profiles
-- посреди неатомарного скрипта — это риск потери данных ради косметики.
-- На значение никто не полагается: и репозиторий, и импорт, и API пишут
-- status явно, а свежие БД получают DEFAULT 'free' из schema.sql.

UPDATE profiles SET status = 'free' WHERE status = 'new';

ALTER TABLE profiles ADD COLUMN fields TEXT NOT NULL DEFAULT '{}';
