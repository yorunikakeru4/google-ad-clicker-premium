"""Политика CAPTCHA: словарь ``behavior.captcha_policy`` (план.md, §5, фаза 8).

Единственное место правды для значений поля и его дефолта: его же читают
``engine.control_plane.config`` (валидация enum), ``config_reader`` (дефолт
для старых ``config.json``) и ``search_controller`` (сама политика). Второй
словарь значений здесь недопустим — по образцу ``engine.proxy_transport``.

Значения:

``stop``
    Дефолт. Событие + скриншот + telegram и сценарий останавливается, ждёт
    оператора (семантика legacy-ветки «нет ключа»).
``solve``
    Авто-решение через 2captcha; исчерпание лимита, таймаут, неудача или
    отсутствие ключа уводят в stop-ветку.
``both``
    Решает, но любая неудача/исчерпание лимита — stop-ветка.

Внимание на семантику: раньше legacy при наличии ключа решал капчу сам и
продолжал прогон. С дефолтом ``stop`` это меняется — авто-решение включается
только явным ``solve``/``both`` (план §5, фаза 8: «stop — по умолчанию»).
"""

CAPTCHA_POLICIES = frozenset({"stop", "solve", "both"})

DEFAULT_CAPTCHA_POLICY = "stop"
